// Local design review only. Blocks HTTP(S); never navigates to Taobao.
const fs=require('fs');
const path=require('path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'/Users/dengtong/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1600,height:1100},deviceScaleFactor:1});
 page.setDefaultTimeout(5000);
 const errors=[],checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route(/^https?:/,route=>{errors.push('Unexpected external request');return route.abort()});
 const base='file://'+path.join(__dirname,'prototype.html');
 for(const board of ['interactive','overview','flow','skins-light','skins-dark','states','edge']){
  await page.goto(base+'?board='+board);
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete));
  const broken=await page.locator('img').evaluateAll(images=>images.filter(i=>!i.naturalWidth).map(i=>i.src));
  assert.deepEqual(broken,[],board+' missing assets');
  const overflow=await page.locator('.phone').evaluateAll(phones=>phones.map(p=>({width:p.clientWidth,children:[...p.querySelectorAll('.panel,.product-card,.dock,.content,.nav')].filter(e=>{const r=e.getBoundingClientRect(),b=p.getBoundingClientRect();return r.width>0&&(r.right>b.right+1||r.left<b.left-1)}).map(e=>e.className)})).filter(p=>p.children.length));
  assert.deepEqual(overflow,[],board+' body overflow');
  await page.screenshot({path:path.join(__dirname,board+'.png'),fullPage:true});
  if(board==='interactive')await page.locator('.phone').screenshot({path:path.join(__dirname,'square-main.png')});
  checks.push(board+': local assets and panel bounds');
 }
 await page.goto(base+'?board=interactive');
 const phone=page.locator('.phone');
 await phone.locator('[data-action="kind:尾款"]').click();
 assert.equal(await phone.locator('[data-action^="card-add:"]').count(),2);
 assert.equal(await phone.getByText('加入衣橱',{exact:true}).count(),0);
 await phone.locator('[data-action="card-add:pilgrim-balance"]').click();
 await phone.getByText('与我的衣橱',{exact:true}).waitFor();
 assert.equal(await phone.getByText('保存到心愿',{exact:true}).count(),0);
 checks.push('tail has no add/save/payment action');
 await page.evaluate(()=>phones[0].open('dorothy-cotton'));
 await phone.locator('[data-action="add"]').click();
 await phone.locator('.style-select').selectOption('蓝色 JSK');
 await phone.locator('[data-action="size:M"]').click();
 await phone.locator('[data-action="confirm"]').click();
 assert.equal(await phone.locator('.reference-check').isChecked(),false);
 assert.equal(await phone.locator('.category-select').inputValue(),'JSK');
 await phone.locator('.reference-check').check();
 await phone.locator('[data-action="save"]').click();
 await phone.getByText('已加入心愿',{exact:true}).waitFor();
 checks.push('exact SKU -> confirmed category -> optional reference -> simulated wish save');
 await phone.locator('[data-action="feed"]').click();
 await phone.locator('[data-action="kind:全部"]').click();
 await phone.locator('[data-action="card-add:dorothy-cotton"]').click();
 assert.equal(await phone.locator('.style-select').inputValue(),'蓝色 JSK');
 await phone.locator('[data-action="confirm"]').click();
 await phone.locator('[data-action="save"]').click();
 await phone.getByText('这个规格已经登记过',{exact:false}).waitFor();
 checks.push('selection retained; repeated add prompts instead of silent duplicate');
 await page.evaluate(()=>{phones[0].open('liana');phones[0].action('add')});
 await phone.locator('.style-select').selectOption('十字op长款紫色');
 await phone.locator('[data-action="size:XS"]').click();
 await phone.getByText('无货',{exact:true}).waitFor();
 checks.push('unavailable SKU retains factual stock while allowing wish');
 await page.evaluate(()=>phones[0].open('dorothy-cotton'));
 await phone.locator('[data-action="chart"]').click();
 await phone.locator('.viewer img').waitFor();
 assert.equal(await phone.locator('.viewer img').evaluate(i=>i.naturalWidth),1440);
 await phone.locator('.viewer img').click();
 assert.equal(await phone.locator('.viewer.zoom').count(),1);
 checks.push('real chart; full fit, zoom and close');
 await page.goto(base+'?board=interactive');
 await phone.locator('[data-action="search"]').click();
 await phone.locator('.search-input').fill('没有这样的商品');
 await phone.getByText('没有符合条件的动态',{exact:true}).waitFor();
 await phone.locator('[data-action="reset"]').click();
 assert.equal(await phone.locator('.product-card').count(),10);
 checks.push('search-empty reset restores complete event list');
 assert.deepEqual(errors,[]);
 const result={date:'2026-11-05',scope:'local HTML concept only; no Compose, native IME or real wardrobe writes',externalRequests:0,errors,checks};
 fs.writeFileSync(path.join(__dirname,'review.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result,null,2));
 await browser.close();
})().catch(async e=>{console.error(e);await browser?.close();process.exit(1)});
