#!/usr/bin/env python3
"""Freeze released migration implementations for the multi-upgrade regression.

Reads immutable local release tags, never downloads or mutates a user's database.
Only package/object names and visibility are changed; migration bodies are retained.
"""
import hashlib
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCAL = 'app/src/main/java/com/lolita/app/data/local/'
OUT = ROOT / 'app/src/androidTest/java/com/lolita/app/data/history/ReleasedUpgradeMigrations.kt'
parts = ['''package com.lolita.app.data.history

import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

// Generated by scripts/generate_historical_migration_fixture.py.
// TEST ONLY: these released bodies intentionally do not follow later production edits.
''']


def read(tag, name):
    source = subprocess.check_output(['git', 'show', f'{tag}:{LOCAL}{name}.kt'], cwd=ROOT, text=True)
    commit = subprocess.check_output(['git', 'rev-parse', f'{tag}^{{commit}}'], cwd=ROOT, text=True).strip()
    parts.append(f'// {tag} @ {commit}; {name}.kt sha256={hashlib.sha256(source.encode()).hexdigest()}\n')
    return source


def helper(tag, name, replacements):
    source = read(tag, name)
    body = re.sub(r'^package .*\n|^import .*\n', '', source, flags=re.M).strip()
    for old, new in replacements.items():
        body = re.sub(rf'\b{old}\b', new, body)
    body = re.sub(r'\binternal\b', 'private', body)
    parts.append(body + '\n\n')


helper('v2.38.0', 'MigrationDataGuard', {'MigrationDataGuard': 'ReleasedGuard'})
for tag, label in [('v2.38.0', 'Order238'), ('v2.39.1', 'Order2391'), ('v2.39.2', 'Order2392')]:
    helper(tag, 'OrderMigration', {'OrderMigration': label, 'MigrationDataGuard': 'ReleasedGuard'})

source = read('v2.53.0', 'LolitaDatabase')
late_blocks = []
for start in range(23, 29):
    match = re.search(rf'(?m)^        (?:internal|private) val MIGRATION_{start}_{start+1}\s*=', source)
    assert match, start
    end = re.search(r'(?m)^        (?:internal|private) val MIGRATION_|^        fun getDatabase', source[match.end():])
    assert end, start
    block = source[match.start():match.end()+end.start()].rstrip()
    # Remove trailing comments introducing a different migration, keeping the object verbatim.
    block = block[:block.rfind('\n        }') + len('\n        }')]
    late_blocks.append(block.replace('private val', 'val').replace('internal val', 'val'))

for tag, name, new in [
    ('v2.55.0', 'WardrobeMigration', 'ReleasedWardrobe'),
    ('v2.62.0', 'TryOnMaterialMigration', 'ReleasedMaterial'),
    ('v2.63.0', 'MaterialBatchMigration', 'ReleasedBatch'),
    ('v2.68.0', 'OrderImportSessionMigration', 'ReleasedImport'),
    ('v2.70.0', 'AfterSaleMigration', 'ReleasedAfterSale'),
]:
    helper(tag, name, {name: new, 'MIGRATION_32_33': 'released32To33'})

parts.append('''internal object ReleasedUpgradeMigrations {
''' + '\n'.join(late_blocks) + '''
    val all: Array<Migration> = arrayOf(
        object : Migration(20, 21) { override fun migrate(db: SupportSQLiteDatabase) = Order238.migrate(db) },
        object : Migration(21, 22) { override fun migrate(db: SupportSQLiteDatabase) = Order2391.migratePurchaseRecordStatus(db) },
        object : Migration(22, 23) { override fun migrate(db: SupportSQLiteDatabase) = Order2392.persistOrderPurchaseEvidence(db) },
''' + ',\n'.join(f'        MIGRATION_{start}_{start+1}' for start in range(23, 29)) + ''',
        ReleasedWardrobe, ReleasedMaterial, ReleasedBatch, released32To33,
        ReleasedAfterSale.MIGRATION_33_34
    )
''' + '\n}\n')
OUT.write_text('\n'.join(parts))
print(f'Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)')
